// Which game build is running, and where the mod's hard-coded addresses live in it.
//
// Every RVA, prologue and call-site check in mod/src was written against the reference build
// (Retail.exe 0x6ac3e716, Retail.dll 0x6ac3eb69, Steam build of 2026-10-05). Modules keep those
// reference values as their constants and ask this table for the running build's value:
//   game_build::rva(stamp, REFERENCE_RVA)        address in the running build, 0 if not verified
//   game_build::code(stamp, REFERENCE_RVA, actual, EXPECTED)
//                                                 the bytes read at that address are the same code
// EXPECTED is a game_build::Code: the reference RVA, a length and the SHA-256 of the reference
// build's bytes there. The repo and the DLL carry no copy of the game's code, only digests.
// On the reference build code() hashes the bytes read. On a ported build the answer comes from
// GameBuildTable.inc, generated by scripts/gen_game_build_table.py: each entry holds the new RVA,
// the length of the instructions proven equal to the reference code (normalised bytes equal,
// rip/call targets corresponding) and, for that prefix, the XOR of the two builds' bytes, which is
// non-zero only in the moved rip-relative and rel32 fields. Undoing that delta on the bytes read
// gives the reference bytes when the code is the verified port, so the same digest decides. A
// comparison longer than the verified prefix, an address not in the table, or an unknown build all
// fail closed. Signatures for porting the next build are written by the generator to build/, not
// compiled in. See docs/GAME_PATCH_2026-10-21.md.
#include "Sha256.h"

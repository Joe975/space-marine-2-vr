namespace game_build {

enum class Image : uint8_t { exe, dll };

inline constexpr uint32_t REFERENCE_EXE = 0x6ac3e716;
inline constexpr uint32_t REFERENCE_DLL = 0x6ac3eb69;
inline constexpr uint32_t reference_timestamp(Image image) { return image == Image::dll ? REFERENCE_DLL : REFERENCE_EXE; }

// The code a module expects at a reference RVA: `length` bytes with this SHA-256 in the reference
// build. Declare with game_build::hashed(0xRVA, length, "<64 hex digits>"[, Image::dll]).
struct Code {
    uint32_t reference;
    uint16_t length;
    sha256::Digest digest;
    Image image = Image::exe;
    constexpr size_t size() const { return length; }
};
consteval Code hashed(uint32_t reference, uint16_t length, const char (&hex)[65], Image image = Image::exe)
{
    return Code{reference, length, sha256::parse(hex), image};
}

struct Delta {
    uint16_t offset;  // byte within the verified prefix
    uint8_t mask;     // reference byte XOR this build's byte (non-zero)
};
struct Entry {
    uint32_t reference;   // RVA in the reference build
    uint32_t rva;         // RVA in this build
    uint16_t verified;    // bytes of code proven equal from rva (0 for data)
    std::span<const Delta> delta;  // where the verified bytes differ from the reference bytes
};
struct Build {
    Image image;
    uint32_t reference_timestamp, timestamp, size_of_image;
    const char* name;
    std::span<const Entry> entries;
};

#include "GameBuildTable.inc"

inline const Build* ported(uint32_t timestamp, Image image = Image::exe)
{
    for (const auto& b : PORTED_BUILDS)
        if (b.image == image && b.timestamp == timestamp) return &b;
    return nullptr;
}

inline bool known(uint32_t timestamp, Image image = Image::exe)
{
    return timestamp == reference_timestamp(image) || ported(timestamp, image) != nullptr;
}

inline const Entry* entry(const Build& build, uintptr_t reference)
{
    const auto it = std::lower_bound(build.entries.begin(), build.entries.end(), reference,
                                     [](const Entry& e, uintptr_t r) { return e.reference < r; });
    return it != build.entries.end() && it->reference == reference ? &*it : nullptr;
}

// RVA of `reference` in the build with this timestamp; 0 when the build or address is not verified.
inline uintptr_t rva(uint32_t timestamp, uintptr_t reference, Image image = Image::exe)
{
    if (timestamp == reference_timestamp(image)) return reference;
    const auto* b = ported(timestamp, image);
    const auto* e = b ? entry(*b, reference) : nullptr;
    return e ? e->rva : 0;
}

// ---- Unit tests: synthetic code ------------------------------------------------------------
// Module tests can't hold the game's bytes either. In synthetic mode (tests only; the game never
// enables it) the reference build's code at (image, RVA) is a fixed pseudo-random byte stream, and
// code()/same() compare against that stream instead of the digests. testing::bytes() returns it
// (and turns the mode on); testing::ported() returns its port to a table build, the stream with
// that entry's delta applied, for as many bytes as the entry verified.
namespace testing {
namespace detail {
inline std::atomic<bool>& on() { static std::atomic<bool> v{false}; return v; }
}
inline void synthetic(bool enabled = true) { detail::on() = enabled; }
inline bool synthetic_enabled() { return detail::on(); }
inline std::vector<uint8_t> stream(uintptr_t reference, size_t length, Image image = Image::exe)
{
    std::vector<uint8_t> out(length);
    uint64_t x = (uint64_t(reference) << 1 | uint64_t(image)) * 0x9e3779b97f4a7c15ull ^ 0xd1b54a32d192ed03ull;
    for (auto& b : out) { x ^= x << 13; x ^= x >> 7; x ^= x << 17; b = uint8_t(x >> 24); }
    return out;
}
inline std::vector<uint8_t> bytes(const Code& code)
{
    synthetic();
    return stream(code.reference, code.length, code.image);
}
template <size_t N> std::array<uint8_t, N> array(const Code& code)
{
    std::array<uint8_t, N> out{};
    const auto b = bytes(code);
    std::copy_n(b.begin(), (std::min)(N, b.size()), out.begin());
    return out;
}
}

// True when `actual` starts with the reference build's code for `expected`.
inline bool same(std::span<const uint8_t> actual, const Code& expected)
{
    if (actual.size() < expected.size()) return false;
    const auto head = actual.first(expected.size());
    if (testing::synthetic_enabled()) {
        const auto want = testing::stream(expected.reference, expected.size(), expected.image);
        return std::equal(want.begin(), want.end(), head.begin());
    }
    return sha256::hash(head) == expected.digest;
}

// True when `actual` (read at rva(timestamp, reference)) starts with the code the module expects:
// the reference build's code itself, or on a ported build its verified port.
inline bool code(uint32_t timestamp, uintptr_t reference, std::span<const uint8_t> actual, const Code& expected,
                 Image image = Image::exe)
{
    if (reference != expected.reference || image != expected.image || actual.size() < expected.size()) return false;
    if (timestamp == reference_timestamp(image)) return same(actual, expected);
    const auto* b = ported(timestamp, image);
    const auto* e = b ? entry(*b, reference) : nullptr;
    if (!e || e->verified < expected.size()) return false;
    std::vector<uint8_t> undone(actual.begin(), actual.begin() + expected.size());
    for (const auto& d : e->delta)
        if (d.offset < undone.size()) undone[d.offset] ^= d.mask;
    return same(undone, expected);
}

namespace testing {
// The synthetic code at `reference` as ported to the table build `timestamp` (all verified bytes).
inline std::vector<uint8_t> ported(uint32_t timestamp, uintptr_t reference, Image image = Image::exe)
{
    synthetic();
    const auto* b = game_build::ported(timestamp, image);
    const auto* e = b ? entry(*b, reference) : nullptr;
    if (!e) return {};
    auto out = stream(reference, e->verified, image);
    for (const auto& d : e->delta) out[d.offset] ^= d.mask;
    return out;
}
}

// ---- The running process -------------------------------------------------------------------
// The build that rva(reference)/code(reference, ...) without a timestamp refer to. In the game it
// is the exe's own PE timestamp; in any other process (unit tests, tools) it is the reference
// build, so module logic tested against reference constants keeps its meaning.
namespace detail {
inline std::atomic<uint32_t>& override_slot() { static std::atomic<uint32_t> v{0}; return v; }
inline uint32_t identify_process()
{
#ifdef _WIN32
    const auto base = reinterpret_cast<const uint8_t*>(GetModuleHandleW(nullptr));
    wchar_t path[MAX_PATH]{};
    GetModuleFileNameW(nullptr, path, MAX_PATH);
    const std::wstring_view p{path};
    if (base && p.ends_with(L"Space Marine 2 - Retail.exe")) {
        const auto dos = reinterpret_cast<const IMAGE_DOS_HEADER*>(base);
        const auto nt = reinterpret_cast<const IMAGE_NT_HEADERS64*>(base + dos->e_lfanew);
        return nt->FileHeader.TimeDateStamp;
    }
#endif
    return REFERENCE_EXE;
}
}

inline uint32_t active()
{
    if (const auto o = detail::override_slot().load()) return o;
    static const uint32_t stamp = detail::identify_process();
    return stamp;
}
// Tests only: pretend the process is this exe build (0 restores detection).
inline void override_active_for_testing(uint32_t timestamp) { detail::override_slot().store(timestamp); }

// A module that reads with the active-build overloads below may proceed only on a known build that
// is also the one this process is running.
inline bool supported(uint32_t timestamp) { return known(timestamp) && timestamp == active(); }
inline uintptr_t rva(uintptr_t reference) { return rva(active(), reference); }
inline bool code(uintptr_t reference, std::span<const uint8_t> actual, const Code& expected)
{
    return code(active(), reference, actual, expected);
}
inline const char* name(uint32_t timestamp, Image image = Image::exe)
{
    if (timestamp == reference_timestamp(image)) return "2026-10-05 (reference)";
    const auto* b = ported(timestamp, image);
    return b ? b->name : "unknown";
}

} // namespace game_build
